/**
 * Generates supabase/migrations/20261102000400_reference_data.sql from the TypeScript sources of truth
 * (game-engine rules/ranks, campaigns template, training exercises).
 *   pnpm gen:reference          writes the file
 *   pnpm gen:reference --check  fails (exit 1) if the committed file is stale (used in CI)
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { RULES_V1, RANK_META, RANK_REQUIREMENTS_V1 } from "../packages/game-engine/src/index";
import { AGOGE_9 } from "../packages/campaigns/src/index";
import { EXERCISES } from "../packages/training/src/index";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../supabase/migrations/20261102000400_reference_data.sql");
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(",")}]::text[]` : `'{}'::text[]`);

const rulesJson = JSON.stringify(RULES_V1);
const lines: string[] = [];
const out = (s = "") => lines.push(s);

out("-- GENERATED by scripts/gen-reference-sql.ts — do not edit by hand. Re-run `pnpm gen:reference`.");
out("-- Balance changes ship as a NEW rules version in a NEW migration; existing versions are immutable.");
out();
out(`insert into public.game_rule_versions (id, effective_at, rules, checksum) values (${RULES_V1.version}, '2026-11-01T00:00:00Z', ${j(RULES_V1)}, ${q(createHash("md5").update(rulesJson).digest("hex"))}) on conflict (id) do nothing;`);
out();
for (const r of RANK_META) out(`insert into public.rank_definitions (rank_key, ordinal, name, note) values (${q(r.rankKey)}, ${r.ordinal}, ${q(r.name)}, ${q(r.note)}) on conflict (rank_key) do nothing;`);
out();
for (const r of RANK_REQUIREMENTS_V1) out(`insert into public.rank_requirements (rank_key, rules_version, min_qualified_days, min_lifetime_xp, requires_trial, min_evidence_level) values (${q(r.rankKey)}, ${r.rulesVersion}, ${r.minQualifiedDays}, ${r.minLifetimeXp}, ${r.requiresTrial}, ${q(r.minEvidenceLevel)}) on conflict do nothing;`);
out();
out(`insert into public.campaign_templates (key, name, rules_version, lifecycle, total_qualifying_days) values ('agoge-9', 'Agōgē: The First Nine', ${RULES_V1.version}, 'live', 9) on conflict (key) do nothing;`);
for (const d of AGOGE_9) {
  const spec = { primary: d.primary, side: d.side, alternatives: d.alternatives, theme: d.theme };
  out(`insert into public.campaign_day_templates (template_id, day_number, focus, title, description, quest_spec) select id, ${d.day}, ${q(d.focus)}, ${q(d.title)}, ${q(d.description)}, ${j(spec)} from public.campaign_templates where key = 'agoge-9' on conflict (template_id, day_number) do nothing;`);
}
out();
for (const e of EXERCISES) out(`insert into public.exercise_catalog (slug, name, movement_pattern, category, equipment, instructions, alternatives) values (${q(e.slug)}, ${q(e.name)}, ${q(e.movementPattern)}, ${q(e.category)}, ${q(e.equipment)}, ${q(e.instructions)}, ${arr(e.alternatives)}) on conflict (slug) do nothing;`);
out();
const quests = [["strength", 60], ["cardio", 60], ["mobility", 15], ["skill", 60], ["logging", 15], ["reflection", 10], ["recovery", 60], ["custom", 15]] as const;
for (const [t, xp] of quests) out(`insert into public.quest_templates (key, type, default_xp) values (${q(t)}, ${q(t)}, ${xp}) on conflict (key) do nothing;`);
out();
const challenges = [
  ["max-pushups", "Max push-ups (good form)", "pushups", "higher_better", "reps", "Rehearse at ~70% effort the day before. Stop when form breaks."],
  ["timed-mile", "Timed mile (walk or run)", "mile_time", "lower_better", "min", "Build up with easy sessions; walking counts."],
  ["plank-hold", "Plank hold", "plank_seconds", "higher_better", "s", "Stop when your hips sag or you feel pain."],
  ["long-walk", "Longest comfortable walk", "walk_distance", "higher_better", "km", "Bring water; choose a safe, familiar route."],
] as const;
for (const [k, t, m, d, u, g] of challenges) out(`insert into public.challenge_templates (key, title, metric, direction, default_unit, min_prep_guidance) values (${q(k)}, ${q(t)}, ${q(m)}, ${q(d)}, ${q(u)}, ${q(g)}) on conflict (key) do nothing;`);
out();
out(`insert into public.achievement_definitions (key, title, description) values ('first_oath', 'The Oath', 'Completed your first qualifying program day.') on conflict do nothing;`);
out(`insert into public.achievement_definitions (key, title, description) values ('rank_hoplites', 'Hoplitēs', 'Passed your first trial and earned the rank of Hoplitēs.') on conflict do nothing;`);
out(`insert into public.cosmetic_items (key, name, slot, unlock_rank_key) values ('crest_bronze_lambda', 'Bronze Lambda Crest', 'crest', 'hoplites') on conflict do nothing;`);
out(`insert into public.cosmetic_items (key, name, slot, unlock_rank_key) values ('cloak_crimson', 'Crimson Cloak', 'cloak', 'hoplites') on conflict do nothing;`);
out();
const flags = [
  ["phalanx_social", false, "planned", "Friends, squads, feed. Phase 3 — not released."],
  ["healthkit_import", false, "planned", "Apple HealthKit import. Phase 4."],
  ["health_connect_import", false, "planned", "Android Health Connect import. Phase 4."],
  ["campaign_30_60_90", false, "planned", "Day 30/60/90/300 segments. Phase 2."],
  ["demo_clock", false, "feature_flagged", "Dev-only simulated clock. Ignored by the server in production."],
] as const;
for (const [k, e, s, d] of flags) out(`insert into public.feature_flags (key, enabled, status, description) values (${q(k)}, ${e}, ${q(s)}, ${q(d)}) on conflict do nothing;`);

const content = lines.join("\n") + "\n";
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing */ }
  if (current !== content) { console.error("reference_data.sql is stale. Run: pnpm gen:reference"); process.exit(1); }
  console.log("reference_data.sql is up to date");
} else {
  writeFileSync(OUT, content);
  console.log("wrote", OUT);
}
